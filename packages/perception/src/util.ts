import { createHash } from "node:crypto";
import { ZimReaperError } from "@zimreaper/protocol";

export function shortHash(input: string, length = 12): string {
  return createHash("sha1").update(input).digest("hex").slice(0, length);
}

export function collapseWhitespace(value: string): string {
  return value.replace(/\s+/g, " ").trim();
}

/** Compact, single-line, quote-safe rendering of page text for the model. */
export function quote(value: string, maxLength = 120): string {
  const text = collapseWhitespace(value);
  const clipped =
    text.length > maxLength ? `${text.slice(0, Math.max(0, maxLength - 1))}…` : text;
  return `"${clipped.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

/** CSS.escape-compatible enough for ids and class tokens (no DOM in Node). */
export function escapeCssIdent(value: string): string {
  let out = "";
  for (let i = 0; i < value.length; i += 1) {
    const ch = value.charAt(i);
    const code = value.charCodeAt(i);
    if (code === 0x00) {
      out += "\uFFFD";
      continue;
    }
    const isDigit = code >= 0x30 && code <= 0x39;
    const isAlpha = (code >= 0x41 && code <= 0x5a) || (code >= 0x61 && code <= 0x7a);
    const isSafe = isAlpha || isDigit || code === 0x2d || code === 0x5f || code >= 0x80;
    if (isDigit && (i === 0 || (i === 1 && value.charCodeAt(0) === 0x2d))) {
      out += `\\${code.toString(16)} `;
      continue;
    }
    out += isSafe ? ch : `\\${ch}`;
  }
  return out;
}

const UNSTABLE_CLASS_PREFIXES = ["css-", "sc-", "jsx-", "emotion-", "styled-", "svelte-", "astro-", "jss", "makeStyles"];

/**
 * Class names generated by CSS-in-JS / CSS modules are the fastest way to make a
 * selector rot between builds, so only keep tokens that look hand-written.
 */
export function isStableClassToken(token: string): boolean {
  if (token.length === 0 || token.length > 40) return false;
  if (!/^[A-Za-z][A-Za-z0-9_-]*$/.test(token)) return false;
  const lower = token.toLowerCase();
  if (UNSTABLE_CLASS_PREFIXES.some((prefix) => lower.startsWith(prefix))) return false;
  if (token.includes("__")) return false;
  if (/[0-9a-f]{8,}/i.test(token)) return false;
  const digits = (token.match(/\d/g) ?? []).length;
  if (digits >= 4) return false;
  // "button2Xf" / "rowA1b2"-style module hashes.
  if (digits > 0 && /^[a-z]{1,4}[A-Z0-9]/.test(token)) return false;
  return true;
}

export function messageOf(err: unknown): string {
  if (err instanceof Error) return err.message;
  if (typeof err === "string") return err;
  try {
    return JSON.stringify(err);
  } catch {
    return String(err);
  }
}

/** Every browser await gets a deadline; a hung CDP socket must not hang an agent loop. */
export function withDeadline<T>(promise: Promise<T>, ms: number, label: string): Promise<T> {
  if (!Number.isFinite(ms) || ms <= 0) return promise;
  return new Promise<T>((resolve, reject) => {
    const timer = setTimeout(() => {
      reject(new ZimReaperError("TIMEOUT", `${label} exceeded ${ms}ms`, { retryable: true }));
    }, ms);
    timer.unref?.();
    promise.then(
      (value) => {
        clearTimeout(timer);
        resolve(value);
      },
      (err: unknown) => {
        clearTimeout(timer);
        reject(err);
      },
    );
  });
}

/** Bounded concurrency for the per-node box-model fan-out. */
export async function mapLimit<T, R>(
  items: readonly T[],
  limit: number,
  fn: (item: T) => Promise<R>,
): Promise<R[]> {
  const results: R[] = new Array<R>(items.length);
  let cursor = 0;
  const workers = Math.max(1, Math.min(limit, items.length));
  const run = async (): Promise<void> => {
    for (;;) {
      const index = cursor;
      cursor += 1;
      if (index >= items.length) return;
      const item = items[index] as T;
      results[index] = await fn(item);
    }
  };
  await Promise.all(Array.from({ length: workers }, run));
  return results;
}
